package com.piiscan.report.generator;

import com.piiscan.report.dto.ReportDataContainer;
import org.springframework.stereotype.Component;

import java.io.ByteArrayOutputStream;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;

@Component
public class CsvReportGenerator {

    public byte[] generateCsv(ReportDataContainer data) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PrintWriter writer = new PrintWriter(out, true, StandardCharsets.UTF_8);

        // 1. Report Metadata Comment Header
        writer.println("# Privacy Audit & Data Governance Platform");
        writer.println("# Report Title: " + escapeCsv(data.getReportTitle()));
        writer.println("# Generated By: " + escapeCsv(data.getGeneratedBy()));
        writer.println("# Generated At: " + escapeCsv(data.getGeneratedAt().toString()));
        writer.println("# Date Range: " + escapeCsv(data.getDateFrom().toString()) + " to " + escapeCsv(data.getDateTo().toString()));
        writer.println("# Database Target: " + escapeCsv(data.getDatabaseName()));
        writer.println("# Security Assurance: Metadata only. Zero raw PII persisted.");
        writer.println();

        List<Map<String, Object>> rows = data.getRows();

        if (rows != null && !rows.isEmpty()) {
            // 2. CSV Column Headers
            Map<String, Object> firstRow = rows.get(0);
            StringBuilder headerLine = new StringBuilder();
            int i = 0;
            for (String colName : firstRow.keySet()) {
                if (i > 0) headerLine.append(",");
                headerLine.append(escapeCsv(formatColHeader(colName)));
                i++;
            }
            writer.println(headerLine.toString());

            // 3. CSV Data Rows
            for (Map<String, Object> row : rows) {
                StringBuilder rowLine = new StringBuilder();
                int j = 0;
                for (Object val : row.values()) {
                    if (j > 0) rowLine.append(",");
                    rowLine.append(escapeCsv(val != null ? val.toString() : ""));
                    j++;
                }
                writer.println(rowLine.toString());
            }
        } else {
            writer.println("Status,Message");
            writer.println("NO_DATA,No findings found matching the selected report parameters.");
        }

        writer.flush();
        return out.toByteArray();
    }

    private String escapeCsv(String value) {
        if (value == null) return "";
        String str = value.trim();
        if (str.contains(",") || str.contains("\"") || str.contains("\n") || str.contains("\r")) {
            str = str.replace("\"", "\"\"");
            return "\"" + str + "\"";
        }
        return str;
    }

    private String formatColHeader(String raw) {
        if (raw == null) return "";
        StringBuilder sb = new StringBuilder();
        for (char c : raw.toCharArray()) {
            if (Character.isUpperCase(c)) {
                sb.append(" ").append(c);
            } else {
                sb.append(c);
            }
        }
        return sb.toString().toUpperCase().trim();
    }
}
